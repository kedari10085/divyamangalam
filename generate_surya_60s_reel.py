def create_432hz_drone(wav_path, duration=60.0, sample_rate=44100):
    n_samples = int(sample_rate * duration)
    with wave.open(wav_path, 'w') as wav:
        wav.setnchannels(1)
        wav.setsampwidth(2)
        wav.setframerate(sample_rate)
        for i in range(n_samples):
            t = i / sample_rate
            env = 1.0
            if t < 1.5: env = t / 1.5
            elif t > duration - 2.0: env = (duration - t) / 2.0
            
            # 432 Hz + 108 Hz + 216 Hz solar harmonics
            val = (
                0.38 * math.sin(2 * math.pi * 432 * t) +
                0.32 * math.sin(2 * math.pi * 108 * t) +
                0.30 * math.sin(2 * math.pi * 216 * t)
            ) * env
            sample = int(val * 16000)
            wav.writeframes(struct.pack('<h', sample))

async def synthesize_surya_voiceover(text, output_mp3):
    if not HAS_EDGE_TTS:
        return False
    try:
        # MadhurNeural speaks in a calm, authoritative, devotional cadence
        comm = edge_tts.Communicate(text, 'hi-IN-MadhurNeural', rate='-8%', pitch='-2Hz')
        await comm.save(output_mp3)
        return True
    except Exception as e:
        print(f"Warning: Edge-TTS synthesis failed ({e}), using 432Hz drone only.")
        return False

